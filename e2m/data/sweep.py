"""Sweep compiler settings and keep harness-verified machine-code variants.

Run ``python -m e2m.data.sweep``. Configs already present in
``data/sweep-cache.jsonl`` are skipped, so a killed run resumes.

Generated bytes are assembled and executed only inside the Unicorn harness.
"""

from __future__ import annotations

import argparse
import json
import multiprocessing as mp
import os
import sys
import time
import traceback
from pathlib import Path
from typing import Any

from e2m.data.aggregate import load_cache, write_outputs
from e2m.data.compile import (
    CompileError,
    apply_function_attrs,
    compile_c_asm,
    compile_c_ir,
    compile_rust_asm,
    find_tool,
    opt_llc_asm,
    tool_version,
)
from e2m.data.extract import ExtractError, extract_function_asm, unsupported_instruction
from e2m.data.grid import build_jobs
from e2m.harness.assemble import AssembleError, assemble
from e2m.harness.tasks import load_jsonl, run_task

GRID_NOTE_REDUCED = """\
Reduced C grid (see `e2m/data/grid.py`):

- **gcc / clang**: `-O0,-O2,-O3,-Os` × march `x86-64`, `x86-64-v3` × feature bundles (default, `-mno-avx -mno-avx2`, `-mavx2`) × toggles (default, unroll, no-vectorize).
- rustc is omitted on the scaled-task run (C sources only).
- llvm-opt default pipelines only (no random seeds) when requested.

Fixed C flags on every gcc/clang compile: `-fno-asynchronous-unwind-tables -fno-unwind-tables -fcf-protection=none -fno-stack-protector -fno-pic -ffreestanding -m64`.
"""

GRID_NOTE = """\
Cartesian grids (see `e2m/data/grid.py`):

- **gcc / clang**: `-O0,-O1,-O2,-O3,-Os,-Oz` × march `x86-64`, `x86-64-v2`, `x86-64-v3`, `znver3` × feature bundles (default, `-mno-avx -mno-avx2`, 128-bit AVX without FMA, plain `-mavx2`, SSE2-only) × toggles (unroll on/off, vectorize on/off, inline-insns 1 and 1000, no alignment).
- **rustc**: `opt-level` `0,1,2,3,s,z` × the same four CPUs × feature bundles (`+avx2`, `-avx,-avx2`, `+avx2,-fma`, SSE2-only, default) × `overflow-checks` off/on × LLVM args (unroll threshold, inline threshold, vectorize-loops off). Built as `#![no_std]` + panic handler, `-C panic=abort`, `--emit=asm`.
- **llvm-opt** (when `clang`, `opt`, and `llc` exist): unoptimized IR (`-disable-O0-optnone`), then `default<O0>`…`default<O3>` and N random new-PM pass pipelines (`--llvm-seeds`). LLVM 23 has no `-Os`/`-Oz` and no `default<Os>`; the size rows are `default<O2>` plus `optsize` / `minsize` function attributes. `llc` gets `-O0`…`-O3` and `-mcpu`.

Fixed C flags on every gcc/clang compile: `-fno-asynchronous-unwind-tables -fno-unwind-tables -fcf-protection=none -fno-stack-protector -fno-pic -ffreestanding -m64`.
"""

_TASKS: dict[str, dict[str, Any]] = {}
_TOOLS: dict[str, str] = {}
_IR: dict[str, str] = {}


def _init(task_dicts: list[dict[str, Any]], tools: dict[str, str]) -> None:
    global _TASKS, _TOOLS
    _TASKS = {t["id"]: t for t in task_dicts}
    _TOOLS = dict(tools)


def _classify_extract(exc: ExtractError) -> str:
    msg = exc.message.lower()
    if "call" in msg or "jump to external" in msg:
        return "external_call"
    if "reloc" in msg or "undefined" in msg or "unresolved" in msg:
        return "external_reloc"
    return "extract"


def _classify_assemble(exc: AssembleError) -> str:
    msg = str(exc).lower()
    if "external" in msg or "undefined" in msg or "reloc" in msg or "got" in msg:
        return "external_reloc"
    return "assemble_error"


def _fail(job: dict[str, Any], reason: str, detail: str) -> dict[str, Any]:
    return {
        "config_id": job["config_id"],
        "task_id": job["task_id"],
        "compiler": job["compiler"],
        "flags": list(job["flags"]),
        "seed": job.get("seed"),
        "passes": job.get("passes"),
        "knobs": job.get("knobs") or {},
        "status": "fail",
        "reason": reason,
        "detail": detail[:500],
    }


def _llc_opt_flag(job: dict[str, Any], knobs: dict[str, Any]) -> str:
    """Return an llc ``-O*`` flag. Pipeline names are not optimization levels."""
    raw = str(knobs.get("opt") or "")
    if raw.startswith("-O"):
        return raw
    for flag in job.get("flags") or []:
        text = str(flag)
        if text.startswith("-O"):
            return text
    return "-O2"


def _compile_asm(job: dict[str, Any], source_c: str, source_rust: str) -> str:
    compiler = job["compiler"]
    if compiler in {"gcc", "clang"}:
        return compile_c_asm(source_c, _TOOLS[compiler], list(job["flags"]))
    if compiler == "rustc":
        if not source_rust.strip():
            raise CompileError("task has no Rust reference")
        return compile_rust_asm(source_rust, _TOOLS["rustc"], list(job["flags"]))
    if compiler == "llvm-opt":
        ir = _IR.get(job["task_id"])
        if ir is None:
            ir = compile_c_ir(source_c, _TOOLS["clang"])
            _IR[job["task_id"]] = ir
        knobs = job.get("knobs") or {}
        ir_attrs = str(knobs.get("ir_attrs") or "")
        if ir_attrs:
            ir = apply_function_attrs(ir, ir_attrs)
        passes = knobs.get("passes") or "default<O2>"
        # Default pipelines store the new-PM label (default<O2>, default<Os>, …)
        # in knobs["opt"]. llc on LLVM 23 accepts only -O0/-O1/-O2/-O3. The
        # recorded flags carry that real level; random seeds store it directly.
        llc_flags = [
            _llc_opt_flag(job, knobs),
            f"-mcpu={knobs.get('cpu') or 'x86-64'}",
        ]
        return opt_llc_asm(
            ir,
            opt_bin=_TOOLS["opt"],
            llc_bin=_TOOLS["llc"],
            passes=passes,
            llc_flags=llc_flags,
        )
    raise CompileError(f"unknown compiler {compiler}")


def evaluate_job(job: dict[str, Any]) -> dict[str, Any]:
    """Compile, extract, and verify one config. Safe to call inside a worker."""
    from e2m.harness.tasks import task_from_dict

    raw_task = _TASKS[job["task_id"]]
    task = task_from_dict(raw_task)
    name = task.sig().name
    try:
        asm_raw = _compile_asm(job, task.reference_c, task.reference_rust)
    except CompileError as exc:
        return _fail(job, "compile_error", str(exc))
    except Exception as exc:  # noqa: BLE001
        return _fail(job, "compile_error", f"{exc}\n{traceback.format_exc()[-400:]}")

    try:
        asm = extract_function_asm(asm_raw, name)
    except ExtractError as exc:
        return _fail(job, _classify_extract(exc), exc.message)
    except Exception as exc:  # noqa: BLE001
        return _fail(job, "extract", str(exc))

    try:
        image = assemble(asm, syntax="att")
    except AssembleError as exc:
        return _fail(job, _classify_assemble(exc), str(exc))
    except Exception as exc:  # noqa: BLE001
        return _fail(job, "assemble_error", str(exc))

    entry = image.entry(name)
    off = entry - image.text_addr
    if off < 0 or off > len(image.text):
        return _fail(job, "extract", f"entry {entry:#x} outside text")
    func_bytes = image.text[off:]
    backend = (os.environ.get("E2M_EMU_BACKEND") or "unicorn").strip().lower()
    if backend in {"", "unicorn"}:
        bad = unsupported_instruction(func_bytes, entry)
        if bad:
            return _fail(job, "unsupported_insn", bad)

    # Leading padding would make `off != 0`. Emulate the whole image so any
    # rip-relative rodata still lands, but record only the function bytes.
    timeout_s = float(os.environ.get("E2M_TEST_TIMEOUT") or "0.2")
    count_insns = os.environ.get("E2M_COUNT_INSNS", "1") != "0"
    run = run_task(
        task,
        image,
        syntax="att",
        timeout_s=timeout_s,
        count_instructions=count_insns,
    )
    if not run.passed:
        return _fail(job, "test_fail" if not run.assemble_error else "assemble_error", run.fail_reason)

    per = [c.emu.insn_count for c in run.cases]
    import hashlib

    digest = hashlib.sha256(func_bytes).hexdigest()
    return {
        "config_id": job["config_id"],
        "task_id": job["task_id"],
        "compiler": job["compiler"],
        "flags": list(job["flags"]),
        "seed": job.get("seed"),
        "passes": job.get("passes"),
        "knobs": job.get("knobs") or {},
        "status": "pass",
        "reason": "pass",
        "detail": "",
        "sha256": digest,
        "size": len(func_bytes),
        "insn_count": int(run.insn_count),
        "insn_per_test": per,
        "asm": asm,
        "bytes_hex": func_bytes.hex(),
        "rodata_hex": image.rodata.hex() if image.rodata else "",
    }


def _worker(job: dict[str, Any]) -> dict[str, Any]:
    try:
        return evaluate_job(job)
    except Exception as exc:  # noqa: BLE001
        return _fail(job, "worker_error", f"{exc}\n{traceback.format_exc()[-400:]}")


def _done_ids(rows: list[dict[str, Any]]) -> set[str]:
    return {str(r["config_id"]) for r in rows if r.get("config_id")}


def _task_dicts(path: Path) -> list[dict[str, Any]]:
    tasks = load_jsonl(path)
    out = []
    for task in tasks:
        out.append(
            {
                "id": task.id,
                "spec": task.spec,
                "signature": task.signature,
                "reference_c": task.reference_c,
                "reference_rust": task.reference_rust,
                "tests": [
                    {
                        "args": c.args,
                        "ret": c.expected_return,
                        "bufs": c.expected_buffers,
                        "ret_cmp": c.ret_cmp,
                        "id": c.id,
                    }
                    for c in task.tests
                ],
            }
        )
    return out


def detect_compilers(requested: list[str] | None) -> tuple[list[str], dict[str, str]]:
    names = ("gcc", "clang", "rustc", "opt", "llc")
    found = {name: find_tool(name) for name in names}
    available: list[str] = []
    if found["gcc"]:
        available.append("gcc")
    if found["clang"]:
        available.append("clang")
    if found["rustc"]:
        available.append("rustc")
    if found["clang"] and found["opt"] and found["llc"]:
        available.append("llvm-opt")
    tools = {name: path for name, path in found.items() if path}
    if not requested or requested == ["auto"]:
        return available, tools
    missing = [c for c in requested if c not in available]
    if missing:
        raise SystemExit(
            "compiler not available: "
            + ", ".join(missing)
            + f" (found: {', '.join(available) or 'none'})"
        )
    return requested, tools


def tool_versions(tools: dict[str, str]) -> dict[str, str]:
    versions = {}
    for name, path in tools.items():
        versions[name] = f"{tool_version(path)} ({path})"
    return versions


def run_sweep(
    *,
    tasks_path: Path,
    out_dir: Path,
    jobs: int,
    compilers: list[str],
    llvm_seeds: int,
    limit: int = 0,
    resume: bool = True,
    grid: str = "full",
) -> dict[str, Any]:
    out_dir.mkdir(parents=True, exist_ok=True)
    cache_path = out_dir / "sweep-cache.jsonl"
    task_dicts = _task_dicts(tasks_path)
    task_ids = [t["id"] for t in task_dicts]
    all_jobs = build_jobs(task_ids, compilers, llvm_seeds=llvm_seeds, grid=grid)
    if limit > 0:
        all_jobs = all_jobs[:limit]
    existing = load_cache(cache_path) if resume else []
    done = _done_ids(existing) if resume else set()
    pending = [job for job in all_jobs if job["config_id"] not in done]
    tools = {name: path for name, path in _active_tools(compilers).items()}
    versions = tool_versions(tools)
    (out_dir / "sweep-tools.json").write_text(json.dumps(versions, indent=2) + "\n", encoding="utf-8")

    print(
        f"sweep: {len(all_jobs)} configs, {len(done)} already cached, {len(pending)} to run, {jobs} workers",
        flush=True,
    )
    started = time.time()
    if pending:
        ctx = mp.get_context("spawn")
        cache_fh = cache_path.open("a", encoding="utf-8")
        passed = failed = 0
        try:
            with ctx.Pool(
                processes=max(1, jobs),
                initializer=_init,
                initargs=(task_dicts, tools),
                maxtasksperchild=64,
            ) as pool:
                for i, result in enumerate(pool.imap_unordered(_worker, pending, chunksize=1), 1):
                    cache_fh.write(json.dumps(result, ensure_ascii=False) + "\n")
                    if i % 20 == 0:
                        cache_fh.flush()
                    if result.get("status") == "pass":
                        passed += 1
                    else:
                        failed += 1
                    if i % 100 == 0 or i == len(pending):
                        elapsed = time.time() - started
                        rate = i / elapsed if elapsed else 0
                        print(
                            f"  {i}/{len(pending)} pass={passed} fail={failed} {rate:.1f} cfg/s",
                            flush=True,
                        )
                        (out_dir / "sweep-progress.txt").write_text(
                            f"{i}/{len(pending)} pass={passed} fail={failed}\n",
                            encoding="utf-8",
                        )
        finally:
            cache_fh.flush()
            cache_fh.close()

    rows = load_cache(cache_path)
    # If this process was a limited run, still aggregate the whole cache so
    # resume keeps one consistent dataset. Filter to known config ids of the
    # full grid only when not limited, so a --limit debug run does not delete
    # a previous full report's rows from the jsonl outputs... A limited run
    # should aggregate only what is in the cache. That is correct.
    tasks_by_id = {t["id"]: t for t in task_dicts}
    stats = write_outputs(
        out_dir=out_dir,
        rows=rows,
        tasks_by_id=tasks_by_id,
        tools=versions,
        compilers=compilers,
        grid_note=GRID_NOTE_REDUCED if grid == "reduced" else GRID_NOTE,
    )
    stats["elapsed_s"] = round(time.time() - started, 2)
    stats["pending"] = len(pending)
    print(
        f"wrote {out_dir}/variants.jsonl ({stats['variants']} unique), "
        f"sft.jsonl ({stats['sft']}), pairs.jsonl ({stats['pairs']}), SWEEP_REPORT.md",
        flush=True,
    )
    return stats


def _active_tools(compilers: list[str]) -> dict[str, str]:
    needed = set()
    for compiler in compilers:
        if compiler in {"gcc", "clang", "rustc"}:
            needed.add(compiler)
        elif compiler == "llvm-opt":
            needed.update(["clang", "opt", "llc"])
    found = {}
    for name in needed:
        path = find_tool(name)
        if not path:
            raise SystemExit(f"required tool {name} not found")
        found[name] = path
    return found


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Sweep compilers into verified E2M variants")
    parser.add_argument("--tasks", type=Path, default=Path("tasks/starter.jsonl"))
    parser.add_argument("--out", type=Path, default=Path("data"))
    parser.add_argument("--jobs", type=int, default=min(16, os.cpu_count() or 1))
    parser.add_argument("--llvm-seeds", type=int, default=12)
    parser.add_argument(
        "--compilers",
        default="auto",
        help="comma list: gcc,clang,rustc,llvm-opt or auto",
    )
    parser.add_argument("--limit", type=int, default=0, help="run only the first N pending configs (debug)")
    parser.add_argument("--no-resume", action="store_true")
    parser.add_argument("--aggregate-only", action="store_true")
    parser.add_argument(
        "--grid",
        choices=("full", "reduced"),
        default="full",
        help="full factorial or the reduced C grid for scaled tasks",
    )
    args = parser.parse_args(argv)

    requested = None if args.compilers == "auto" else [c.strip() for c in args.compilers.split(",") if c.strip()]
    compilers, _tools = detect_compilers(requested)
    if not compilers:
        print("no compilers found", file=sys.stderr)
        return 1
    print("compilers:", ", ".join(compilers), flush=True)
    for name, path in _active_tools(compilers).items():
        print(f"  {name}: {tool_version(path)}", flush=True)

    if args.aggregate_only:
        rows = load_cache(args.out / "sweep-cache.jsonl")
        task_dicts = _task_dicts(args.tasks)
        versions_path = args.out / "sweep-tools.json"
        versions = json.loads(versions_path.read_text(encoding="utf-8")) if versions_path.is_file() else {}
        stats = write_outputs(
            out_dir=args.out,
            rows=rows,
            tasks_by_id={t["id"]: t for t in task_dicts},
            tools=versions,
            compilers=compilers,
            grid_note=GRID_NOTE_REDUCED if args.grid == "reduced" else GRID_NOTE,
        )
        print(stats, flush=True)
        return 0

    run_sweep(
        tasks_path=args.tasks,
        out_dir=args.out,
        jobs=args.jobs,
        compilers=compilers,
        llvm_seeds=args.llvm_seeds,
        limit=args.limit,
        resume=not args.no_resume,
        grid=args.grid,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
