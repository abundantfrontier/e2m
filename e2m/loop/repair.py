"""Model-agnostic test-and-retry loop.

`generate` is a callable that takes a chat message list and returns one string.
The harness never executes generated bytes on the host CPU.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Any, Union

from e2m.harness.tasks import Task, TaskRun, assemble_reference, run_task
from e2m.loop.feedback import append_repair, initial_messages, visible_failure
from e2m.loop.split import hidden_tests, task_with_tests, visible_tests
from e2m.train.format import extract_asm, extract_asm_from_c_then_asm, extract_c, score_task_run

GenerateFn = Callable[..., Union[str, list[str]]]


def call_generate(generate: GenerateFn, messages: list[dict[str, str]], n: int = 1) -> list[str]:
    try:
        out = generate(messages, n=n)
    except TypeError:
        out = generate(messages)
        if n > 1 and isinstance(out, str):
            texts = [out]
            for _ in range(n - 1):
                more = generate(messages)
                texts.append(more if isinstance(more, str) else more[0])
            return texts
    if isinstance(out, str):
        return [out]
    return list(out)[:n]

AVX_STATUSES = {"invalid_insn"}


@dataclass
class Attempt:
    call: int
    sample: int
    round: int
    text: str
    ok_visible: bool
    ok_hidden: bool
    ok_full: bool
    category_visible: str
    category_full: str
    size: int = 0
    insn: int = 0
    detail: str = ""
    vis_run: Any = field(default=None, repr=False, compare=False)

    def as_dict(self) -> dict[str, Any]:
        return {
            "call": self.call,
            "sample": self.sample,
            "round": self.round,
            "ok_visible": self.ok_visible,
            "ok_hidden": self.ok_hidden,
            "ok_full": self.ok_full,
            "category_visible": self.category_visible,
            "category_full": self.category_full,
            "size": self.size,
            "insn": self.insn,
            "detail": self.detail[:400],
            "text": self.text[:2000],
        }


@dataclass
class LoopResult:
    task_id: str
    calls: int
    passed_visible: bool
    passed_hidden: bool
    passed_full: bool
    first_visible_call: int | None
    first_hidden_call: int | None
    first_full_call: int | None
    n_visible: int
    n_hidden: int
    n_tests: int
    attempts: list[Attempt] = field(default_factory=list)
    best_pass: dict[str, Any] | None = None

    def as_dict(self) -> dict[str, Any]:
        return {
            "task_id": self.task_id,
            "calls": self.calls,
            "passed_visible": self.passed_visible,
            "passed_hidden": self.passed_hidden,
            "passed_full": self.passed_full,
            "first_visible_call": self.first_visible_call,
            "first_hidden_call": self.first_hidden_call,
            "first_full_call": self.first_full_call,
            "n_visible": self.n_visible,
            "n_hidden": self.n_hidden,
            "n_tests": self.n_tests,
            "attempts": [a.as_dict() for a in self.attempts],
            "best_pass": self.best_pass,
        }


def run_assembled(task: Task, source: Any, *, timeout_s: float = 1.0) -> TaskRun:
    """Unicorn first; QEMU if Unicorn rejects the encoding (AVX / invalid_insn)."""
    run = run_task(task, source, syntax="auto", timeout_s=timeout_s)
    if run.assemble_error:
        return run
    if any(c.emu is not None and c.emu.status in AVX_STATUSES for c in run.cases):
        return run_task(task, source, syntax="auto", timeout_s=timeout_s, backend="qemu")
    return run


def score_text(task: Task, text: str, *, mode: str = "asm", timeout_s: float = 1.0) -> TaskRun:
    if mode == "c":
        code = extract_c(text)
        candidate = Task(
            id=task.id,
            spec=task.spec,
            signature=task.signature,
            reference_c=code,
            tests=task.tests,
            parsed=task.parsed,
        )
        try:
            image = assemble_reference(candidate, opt="-O2")
        except Exception as exc:  # noqa: BLE001
            return TaskRun(
                task_id=task.id,
                passed=False,
                cases=[],
                assemble_error=str(exc),
            )
        return run_assembled(task, image, timeout_s=timeout_s)
    asm = extract_asm_from_c_then_asm(text) if mode == "c-then-asm" else extract_asm(text)
    return run_assembled(task, asm, timeout_s=timeout_s)


def _score_pair(task: Task, text: str, *, mode: str, timeout_s: float) -> tuple[TaskRun, TaskRun, TaskRun | None]:
    vis_list = visible_tests(task)
    hid_list = hidden_tests(task)
    vis_task = task_with_tests(task, vis_list)
    vis_run = score_text(vis_task, text, mode=mode, timeout_s=timeout_s)
    if not vis_run.passed:
        return vis_run, vis_run, None
    if not hid_list:
        return vis_run, vis_run, vis_run
    full_run = score_text(task, text, mode=mode, timeout_s=timeout_s)
    hid_run = score_text(task_with_tests(task, hid_list), text, mode=mode, timeout_s=timeout_s)
    return vis_run, full_run, hid_run


def _record_attempt(
    result: LoopResult,
    task: Task,
    text: str,
    *,
    sample: int,
    rnd: int,
    mode: str,
    timeout_s: float,
    vis_list: list,
    hid_list: list,
) -> Attempt:
    vis_run, full_run, hid_run = _score_pair(task, text, mode=mode, timeout_s=timeout_s)
    vis_scored = score_task_run(vis_run)
    full_scored = score_task_run(full_run)
    ok_vis = bool(vis_run.passed)
    ok_full = bool(full_run.passed)
    if hid_run is None:
        ok_hid = ok_full if not hid_list else False
    else:
        ok_hid = bool(hid_run.passed)
    attempt = Attempt(
        call=result.calls,
        sample=sample,
        round=rnd,
        text=text or "",
        ok_visible=ok_vis,
        ok_hidden=ok_hid,
        ok_full=ok_full,
        category_visible=str(vis_scored.get("category") or "crash"),
        category_full=str(full_scored.get("category") or "crash"),
        size=int(full_scored.get("size") or 0),
        insn=int(full_scored.get("insn") or 0),
        detail=str(vis_scored.get("detail") or ""),
        vis_run=vis_run,
    )
    result.attempts.append(attempt)
    if ok_vis and result.first_visible_call is None:
        result.first_visible_call = result.calls
        result.passed_visible = True
    if ok_hid and result.first_hidden_call is None:
        result.first_hidden_call = result.calls
        result.passed_hidden = True
    if ok_full:
        result.first_full_call = result.calls
        result.passed_full = True
        result.passed_visible = True
        if not hid_list:
            result.passed_hidden = True
            if result.first_hidden_call is None:
                result.first_hidden_call = result.calls
        result.best_pass = {
            "call": result.calls,
            "size": attempt.size,
            "insn": attempt.insn,
            "text": text[:4000],
            "sample": sample,
            "round": rnd,
        }
    return attempt


def repair_task(
    task: Task,
    generate: GenerateFn,
    *,
    k: int = 8,
    rounds: int = 3,
    mode: str = "asm",
    spec: str | None = None,
    timeout_s: float = 1.0,
    batch_initial: bool = False,
) -> LoopResult:
    """Sample up to k candidates, each with up to `rounds` repairs. Stop at first full pass.

    Only visible tests are fed back. Full / hidden scores are for reporting.
    One sampled sequence counts as one model call. `batch_initial` still counts
    k calls; it only changes how the first round is generated.
    """
    used_spec = spec if spec is not None else task.spec
    vis_list = visible_tests(task)
    hid_list = hidden_tests(task)
    result = LoopResult(
        task_id=task.id,
        calls=0,
        passed_visible=False,
        passed_hidden=False,
        passed_full=False,
        first_visible_call=None,
        first_hidden_call=None,
        first_full_call=None,
        n_visible=len(vis_list),
        n_hidden=len(hid_list),
        n_tests=len(task.tests),
    )

    def one(messages, sample, rnd, n=1) -> list[Attempt]:
        texts = call_generate(generate, messages, n=n)
        attempts = []
        for offset, text in enumerate(texts):
            result.calls += 1
            attempts.append(
                _record_attempt(
                    result,
                    task,
                    text,
                    sample=sample + offset,
                    rnd=rnd,
                    mode=mode,
                    timeout_s=timeout_s,
                    vis_list=vis_list,
                    hid_list=hid_list,
                )
            )
            if result.passed_full:
                return attempts
        return attempts

    for sample in range(k):
        if batch_initial and sample > 0:
            break
        messages = initial_messages(used_spec, task.signature, mode=mode)
        n_first = k if batch_initial else 1
        first = one(messages, sample, 0, n=n_first)
        if result.passed_full:
            return result
        # Repair each visible-failing candidate, skipping hidden-only failures.
        repair_queue = []
        for att in first:
            if att.ok_full:
                continue
            if att.ok_visible and not att.ok_full:
                continue
            repair_queue.append(att)
        if batch_initial:
            # One repair chain, prefer an assembled wrong_answer over a parse miss.
            repair_queue.sort(key=lambda a: 0 if a.category_visible == "wrong_answer" else 1)
            repair_queue = repair_queue[:1]
        for att in repair_queue:
            messages = initial_messages(used_spec, task.signature, mode=mode)
            prev = att.text
            vis_run = getattr(att, "vis_run", None)
            if vis_run is None:
                continue
            info = visible_failure(vis_run, vis_list)
            messages = append_repair(messages, prev, info)
            for rnd in range(1, rounds + 1):
                nxt = one(messages, att.sample, rnd, n=1)
                if result.passed_full:
                    return result
                cur = nxt[-1]
                if cur.ok_visible and not cur.ok_full:
                    break
                if rnd >= rounds:
                    break
                vis_run = getattr(cur, "vis_run", None)
                if vis_run is None:
                    break
                info = visible_failure(vis_run, vis_list)
                messages = append_repair(messages, cur.text, info)
    return result


def pass_at_budget(results: list[LoopResult], budget: int, *, field: str = "first_full_call") -> float:
    if not results:
        return float("nan")
    hits = 0
    for row in results:
        call = getattr(row, field)
        if call is not None and int(call) <= budget:
            hits += 1
    return hits / len(results)
